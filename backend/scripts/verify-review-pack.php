<?php

/**
 * Verifies the committed knowledge review pack (TASK REVIEW-PACK).
 *
 * Run from backend/:
 *   php scripts/verify-review-pack.php
 *
 * This is a byte-level check, not a visual one: valid UTF-8, no U+FFFD, real
 * Thai code points, bounded excerpts, every source present, and the generated
 * document's regeneration warning. Output is ASCII so a Windows console cannot
 * hide the result behind a code-page conversion.
 */
$path = $argv[1] ?? __DIR__.'/../docs/KNOWLEDGE-REVIEW-PACK.md';

if (! is_file($path)) {
    fwrite(STDERR, 'Review pack not found: '.$path."\n");
    exit(1);
}

$contents = file_get_contents($path);

if (! is_string($contents)) {
    fwrite(STDERR, "Could not read the review pack.\n");
    exit(1);
}

$errors = [];

if (! mb_check_encoding($contents, 'UTF-8')) {
    $errors[] = 'the file is not valid UTF-8';
}

if (str_contains($contents, "\u{FFFD}")) {
    $errors[] = 'the file contains U+FFFD replacement characters';
}

if (str_contains($contents, "\u{20AC}")) {
    $errors[] = 'the file contains U+20AC (the mojibake marker)';
}

$thai = preg_match_all('/\p{Thai}/u', $contents);

if ($thai === false || $thai < 1000) {
    $errors[] = 'expected real Thai text (at least 1000 Thai code points)';
}

if (! str_contains($contents, 'php artisan knowledge:review-pack')) {
    $errors[] = 'the regeneration command is missing';
}

if (! str_contains($contents, 'do not edit this file by hand')) {
    $errors[] = 'the do-not-edit warning is missing';
}

$sourcesAt = strpos($contents, '## Sources');
$sourcesBody = $sourcesAt === false ? '' : substr($contents, $sourcesAt);

preg_match_all('/^> (.*)$/mu', $sourcesBody, $matches);
$excerpts = $matches[1] ?? [];
$maxExcerpt = 0;

foreach ($excerpts as $excerpt) {
    $length = mb_strlen($excerpt);
    $maxExcerpt = max($maxExcerpt, $length);

    if ($length > 400) {
        $errors[] = 'an excerpt is longer than 400 characters ('.$length.')';
    }
}

if ($excerpts === []) {
    $errors[] = 'no section excerpts were found';
}

$files = glob(__DIR__.'/../database/knowledge/sources/*.json') ?: [];
sort($files);
$missing = [];
$sourceCount = 0;

foreach ($files as $file) {
    $source = json_decode((string) file_get_contents($file), true, 512, JSON_THROW_ON_ERROR);
    $id = (string) ($source['id'] ?? '');
    $sourceCount++;

    if ($id === '' || ! str_contains($contents, '`'.$id.'`')) {
        $missing[] = $id !== '' ? $id : basename($file);
    }
}

if ($missing !== []) {
    $errors[] = 'sources missing from the pack: '.implode(', ', $missing);
}

if ($errors !== []) {
    fwrite(STDERR, "Review pack verification FAILED:\n");
    foreach ($errors as $error) {
        fwrite(STDERR, '  - '.$error."\n");
    }
    exit(1);
}

echo 'Review pack: '.$path."\n";
echo 'UTF-8: valid'."\n";
echo 'U+FFFD: none'."\n";
echo 'Thai code points: '.$thai."\n";
echo 'Sources present: '.$sourceCount.'/'.count($files)."\n";
echo 'Section excerpts: '.count($excerpts).' (max '.$maxExcerpt.' characters)'."\n";
echo "Review pack verification passed.\n";
